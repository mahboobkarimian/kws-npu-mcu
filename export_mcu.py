"""Export the trained int8 model for microcontrollers, and check the C code against PyTorch and the NPU.

  python -I export_mcu.py runs/commands12/int8.pkl [--check]

Writes mcu/generated/:
  kws_model_data.h/.c       layer table + int8 weights (flash) -- the same integers as the NPU's QDQ graph
  kws_frontend_tables.h/.c  Hann window, sparse mel filterbank, DCT, normalisation stats (from kws/features.py)
--check: builds mcu/build/kws_test on the laptop and compares
  (1) C network on the Python int8 inputs   vs the integer reference   (must be 100 % identical)
  (2) C front end + network on raw audio    vs Python front end + network (float front end: tiny differences allowed)
  and builds the Cortex-M4 objects to report flash / RAM.
SPDX-License-Identifier: MIT
"""
import argparse
import os
import pickle
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kws import config as C                                     # noqa: E402
from kws.features import dct_matrix, hann_window, mel_filterbank  # noqa: E402
from kws.quant import POOL_SHIFT, layer_tag, run_int8            # noqa: E402

GEN = os.path.join(HERE, "mcu", "generated")


def c_array(ctype, name, values, per_line=24):
    v = list(np.asarray(values).ravel())
    def ffmt(x):
        t = f"{float(x):.9g}"
        return (t if any(ch in t for ch in ".e") else t + ".0") + "f"      # "1" -> "1.0f" (valid C float literal)
    fmt = ffmt if ctype == "float" else (lambda x: str(int(x)))
    lines = [", ".join(fmt(x) for x in v[i:i + per_line]) for i in range(0, len(v), per_line)]
    return f"const {ctype} {name}[{len(v)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def write_model(P, classes):
    h = ["/* GENERATED by export_mcu.py -- do not edit. int8 DS-CNN parameters. */",
         "#ifndef KWS_MODEL_DATA_H", "#define KWS_MODEL_DATA_H", '#include "dscnn_int8.h"',
         f"#define KWS_NUM_LAYERS {len(P['layers'])}", f"#define KWS_NUM_CLASSES {len(classes)}",
         f"#define KWS_INPUT_FIX {P['f_input']}      /* input  = q * 2^-{P['f_input']} */",
         f"#define KWS_LOGIT_FIX {P['layers'][-1]['f_out']}      /* logits = q * 2^-{P['layers'][-1]['f_out']} */",
         "extern const kws_layer_t KWS_LAYERS[KWS_NUM_LAYERS];",
         "extern const char *const KWS_CLASS_NAMES[KWS_NUM_CLASSES];", "#endif", ""]
    c = ["/* GENERATED by export_mcu.py -- do not edit. */", '#include "kws_model_data.h"', ""]
    c.append("const char *const KWS_CLASS_NAMES[KWS_NUM_CLASSES] = {" + ", ".join(f'"{n}"' for n in classes) + "};\n")
    rows, h_, w_, ch = [], C.N_FRAMES, C.N_MFCC, 1
    for L in P["layers"]:
        tag = layer_tag(L["name"])
        if L["op"] == "avgpool":
            sh = POOL_SHIFT - (L["f_out"] - L["f_in"])
            rows.append(f'  {{"{tag}", KWS_OP_AVGPOOL, {h_}, {w_}, {ch}, 1, 1, {ch}, {h_}, {w_}, 1, 1, 0, 0, '
                        f'0, 0, 0, {sh}, 1}},')
            h_, w_ = 1, 1
            continue
        w = L["w"]                                                     # torch layout [O, I/g, kh, kw]
        oc, _, kh, kw = w.shape
        (sy, sx), (py, px) = L["stride"], L["pad"]
        oh, ow = (h_ + 2 * py - kh) // sy + 1, (w_ + 2 * px - kw) // sx + 1
        if L["groups"] > 1:
            op, wc = "KWS_OP_DWCONV", w[:, 0].transpose(1, 2, 0)          # -> [kh][kw][C]
        else:
            op, wc = "KWS_OP_CONV", w.transpose(0, 2, 3, 1)               # -> [O][kh][kw][I]
        c.append(f"/* {tag}: {op[7:].lower()} {kh}x{kw}/{sy}, {ch}->{oc} ch, f_in {L['f_in']} f_w {L['f_w']} "
                 f"f_b {L['f_b']} f_out {L['f_out']} */")
        c.append("static " + c_array("int8_t", f"{tag}_w", wc))
        c.append("static " + c_array("int8_t", f"{tag}_b", L["b"]))
        rows.append(f'  {{"{tag}", {op}, {h_}, {w_}, {ch}, {oh}, {ow}, {oc}, {kh}, {kw}, {sy}, {sx}, {py}, {px}, '
                    f'{tag}_w, {tag}_b, {L["bias_shift"]}, {L["shift"]}, {int(L["relu"])}}},')
        h_, w_, ch = oh, ow, oc
    c.append("const kws_layer_t KWS_LAYERS[KWS_NUM_LAYERS] = {")
    c += rows
    c.append("};")
    open(os.path.join(GEN, "kws_model_data.h"), "w").write("\n".join(h))
    open(os.path.join(GEN, "kws_model_data.c"), "w").write("\n".join(c) + "\n")


def write_frontend(mean, std, f_input):
    fb = mel_filterbank()                                              # [513, 40]
    start, length, off, wts = [], [], [], []
    for m in range(C.N_MELS):
        nz = np.nonzero(fb[:, m])[0]
        start.append(nz[0]); length.append(len(nz)); off.append(len(wts)); wts += list(fb[nz[0]:nz[-1] + 1, m])
    h = ["/* GENERATED by export_mcu.py -- do not edit. Front-end tables (= kws/features.py). */",
         "#ifndef KWS_FRONTEND_TABLES_H", "#define KWS_FRONTEND_TABLES_H", "#include <stdint.h>",
         f"#define KWS_N_MELS {C.N_MELS}", f"#define KWS_LOG_EPS {C.LOG_EPS:g}f", f"#define KWS_INPUT_FIX {f_input}",
         "extern const float kws_hann[640];", f"extern const uint16_t kws_mel_start[{C.N_MELS}];",
         f"extern const uint16_t kws_mel_len[{C.N_MELS}];", f"extern const uint16_t kws_mel_off[{C.N_MELS}];",
         f"extern const float kws_mel_w[{len(wts)}];", f"extern const float kws_dct[{C.N_MELS * C.N_MFCC}];",
         f"extern const float kws_mean[{C.N_MFCC}];", f"extern const float kws_std[{C.N_MFCC}];", "#endif", ""]
    c = ['/* GENERATED by export_mcu.py -- do not edit. */', '#include "kws_frontend_tables.h"',
         c_array("float", "kws_hann", hann_window()), c_array("uint16_t", "kws_mel_start", start),
         c_array("uint16_t", "kws_mel_len", length), c_array("uint16_t", "kws_mel_off", off),
         c_array("float", "kws_mel_w", np.float32(wts)), c_array("float", "kws_dct", dct_matrix(), 10),
         c_array("float", "kws_mean", np.float32(mean)), c_array("float", "kws_std", np.float32(std))]
    open(os.path.join(GEN, "kws_frontend_tables.h"), "w").write("\n".join(h))
    open(os.path.join(GEN, "kws_frontend_tables.c"), "w").write("\n".join(c))


def check(d, packed, n_clip):
    import torch
    from kws.features import FrontEnd
    from kws.quant import quantize_input
    mcu = os.path.join(HERE, "mcu")
    b = os.path.join(mcu, "build")
    subprocess.run(["make", "-s", "-C", mcu, "build/kws_test"], check=True)
    P, x_q = d["int8"], d["test_inputs"]
    n, ncls = len(x_q), len(d["classes"])
    ref = run_int8(P, x_q)
    x_q.tofile(f"{b}/in.s8")
    r = subprocess.run([f"{b}/kws_test", "net", f"{b}/in.s8", str(n), f"{b}/logits.s8"], capture_output=True,
                       text=True, check=True)
    print(r.stdout.strip())
    cl = np.fromfile(f"{b}/logits.s8", np.int8).reshape(n, ncls)
    res = {"net_identical_pct": float(np.mean(np.all(cl == ref, 1)) * 100), "net_n": n,
           "host_us": r.stdout.strip()}
    print(f"(1) C network vs integer reference on {n} official-test inputs: "
          f"{res['net_identical_pct']:.3f} % identical logits")

    w = np.load(os.path.join(packed, "official_test_wave.npy"))[:n_clip]
    w.tofile(f"{b}/clips.s16")
    r = subprocess.run([f"{b}/kws_test", "clip", f"{b}/clips.s16", str(len(w)), f"{b}/feat.s8", f"{b}/lc.s8"],
                       capture_output=True, text=True, check=True)
    print(r.stdout.strip())
    cf = np.fromfile(f"{b}/feat.s8", np.int8).reshape(len(w), 1, C.N_FRAMES, C.N_MFCC)
    lc = np.fromfile(f"{b}/lc.s8", np.int8).reshape(len(w), ncls)
    front = FrontEnd(torch.from_numpy(d["mean"]), torch.from_numpy(d["std"]))
    pf = quantize_input(front(torch.from_numpy(w.astype(np.float32) / 32768.0)).numpy(), P["f_input"])
    pl = run_int8(P, pf)
    res.update(fe_feat_identical_pct=float(np.mean(cf == pf) * 100),
               fe_feat_maxdiff=int(np.abs(cf.astype(int) - pf).max()),
               fe_clip_logits_identical_pct=float(np.mean(np.all(lc == pl, 1)) * 100),
               fe_argmax_agree_pct=float(np.mean(lc.argmax(1) == pl.argmax(1)) * 100), fe_n=len(w),
               fe_host=r.stdout.strip())
    print(f"(2) C front end vs Python on {len(w)} clips: {res['fe_feat_identical_pct']:.4f} % of int8 features "
          f"identical (max diff {res['fe_feat_maxdiff']} LSB); logits identical for "
          f"{res['fe_clip_logits_identical_pct']:.2f} % of clips; predicted class agrees for "
          f"{res['fe_argmax_agree_pct']:.2f} %")
    for f in ["in.s8", "logits.s8", "clips.s16", "feat.s8", "lc.s8"]:
        os.remove(f"{b}/{f}")
    sizes = {}
    for core in ("cortex-m4", "cortex-m7"):
        r = subprocess.run(["make", "-s", "-C", mcu, core], capture_output=True, text=True, check=True)
        sizes[core] = r.stdout
        print(core, "\n" + r.stdout)
    res["sizes"] = sizes
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("int8_pkl")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--data", default=os.path.join(HERE, "data/packed"))
    ap.add_argument("--n_clip", type=int, default=4890)
    a = ap.parse_args()
    with open(a.int8_pkl, "rb") as fh:
        d = pickle.load(fh)
    os.makedirs(GEN, exist_ok=True)
    write_model(d["int8"], d["classes"])
    write_frontend(d["mean"], d["std"], d["int8"]["f_input"])
    print(f"wrote {GEN}")
    if a.check:
        import json
        res = check(d, a.data, a.n_clip)
        out = os.path.join(os.path.dirname(a.int8_pkl), "mcu_check.json")
        json.dump(res, open(out, "w"), indent=1)
        print("->", out)


if __name__ == "__main__":
    main()
